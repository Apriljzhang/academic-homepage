import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const out = join(__dirname, "..", "public", "training", "202607", "config.js");
mkdirSync(dirname(out), { recursive: true });

const supabaseUrl = (process.env.PUBLIC_SUPABASE_URL || "").replace(/\/$/, "");
const supabaseAnonKey = process.env.PUBLIC_SUPABASE_ANON_KEY || "";

const body = `// Generated by scripts/gen-training-config.mjs — do not edit by hand.
window.TRAINING_CONFIG = {
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  sessionCode: "202607",
};
`;

writeFileSync(out, body);
console.log(
  `[training-config] wrote ${out} (supabase=${supabaseUrl ? "yes" : "no"})`
);
