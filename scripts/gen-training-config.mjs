import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outs = [
  join(__dirname, "..", "public", "service", "training", "app", "config.js"),
  join(__dirname, "..", "public", "training", "202607", "config.js"),
];

// Only enable Supabase live sync when explicitly opted in AND credentials exist.
// Default is local mode so login always works without DB migrations.
const useSb = String(process.env.PUBLIC_TRAINING_USE_SUPABASE || "").toLowerCase() === "1";
const supabaseUrl = useSb ? (process.env.PUBLIC_SUPABASE_URL || "").replace(/\/$/, "") : "";
const supabaseAnonKey = useSb ? process.env.PUBLIC_SUPABASE_ANON_KEY || "" : "";

const body = `// Generated by scripts/gen-training-config.mjs — do not edit by hand.
window.TRAINING_CONFIG = {
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  sessionCode: "202607",
};
`;

for (const out of outs) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body);
  console.log(`[training-config] wrote ${out} (supabase=${supabaseUrl ? "yes" : "no"})`);
}
